def build_database_uri():
    """Assemble a SQLAlchemy URL out of the DB_* environment variables."""
    engine = os.environ.get('DB_ENGINE', 'postgresql+psycopg2')
    dialect = DB_ENGINE_ALIASES.get(engine, engine)
    name = os.environ.get('DB_NAME', '')
    if dialect.startswith('sqlite'):
        if name in ('', ':memory:'):
            return 'sqlite://'
        path = Path(name)
        if not path.is_absolute():
            path = BASE_DIR / path
        return 'sqlite:///{}'.format(path)
    user = os.environ.get('DB_USER', '')
    password = os.environ.get('DB_PASS', '')
    host = os.environ.get('DB_HOST', '')
    port = os.environ.get('DB_PORT', '')
    netloc = user
    if password:
        netloc = '{}:{}'.format(netloc, password)
    if netloc:
        netloc = '{}@'.format(netloc)
    netloc = '{}{}'.format(netloc, host)
    if port:
        netloc = '{}:{}'.format(netloc, port)
    return '{}://{}/{}'.format(dialect, netloc, name)


